-- creation of table
CREATE TABLE if NOT exists employees (
    employee_id INT PRIMARY KEY AUTO_INCREMENT,
    employee_code CHAR(6),
    employee_name VARCHAR(30),
    age TINYINT UNSIGNED,
    number_of_children TINYINT UNSIGNED,
    experience_months MEDIUMINT UNSIGNED,
    salary DECIMAL(10, 2),
    performance_score FLOAT,
    productivity_score DOUBLE,
    department_id INT UNSIGNED,
    employee_status ENUM ('ACTIVE', 'INACTIVE', 'ON_LEAVE', 'RESIGNED'),
    skills
    SET ('JAVA', 'PYTHON', 'MYSQL', 'REACT', 'AWS'),
        gender ENUM ('MALE', 'FEMALE', 'OTHER'),
        date_of_birth DATE,
        joining_date DATE,
        login_time TIME,
        interview_datetime DATETIME,
        birth_year YEAR,
        is_active BOOLEAN,
        short_note TINYTEXT,
        employee_description TEXT,
        training_history MEDIUMTEXT,
        employee_profile LONGTEXT,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
desc employees;
